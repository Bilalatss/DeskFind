void Lang::Set(int choice)
{
    wchar_t forced[8] = {};
    if (GetEnvironmentVariableW(L"DESKFIND_LANG", forced, ARRAYSIZE(forced))) g_current = EqualsNoCase(forced, L"tr") ? &Turkish : &English;
    else if (choice == 1) g_current = &English;
    else if (choice == 2) g_current = &Turkish;
    else g_current = PRIMARYLANGID(GetUserDefaultUILanguage()) == LANG_TURKISH ? &Turkish : &English;
}

const Lang& Lang::Get()
{
    if (!g_current) Set(0);
    return *g_current;
}
